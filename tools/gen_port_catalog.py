#!/usr/bin/env python3
"""Generate PortCatalog.java - IANA-style names + what each port 1-10000 does."""
from pathlib import Path

# port -> (proto T/U/B, name, about)
P = {}

def add(ports, proto, name, about):
    if isinstance(ports, int):
        ports = [ports]
    for p in ports:
        if 1 <= p <= 10000:
            P[p] = (proto, name, about.strip())

